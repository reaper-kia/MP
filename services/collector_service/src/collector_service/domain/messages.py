def no_answer(platform: str) -> str:
    """Таймаут, сеть, 5xx площадки."""
    return f"{platform}: площадка не ответила, повторите позже"


def bad_answer(platform: str) -> str:
    """Площадка ответила, но не так, как ждали (не JSON, неизвестная ошибка)."""
    return f"{platform}: площадка вернула ошибку, повторите позже"


def not_configured(platform: str) -> str:
    return f"{platform}: доступ к площадке не настроен — обратитесь к администратору"


def access_denied(platform: str) -> str:
    """Ключ / токен площадки не принят или истёк."""
    return f"{platform}: ключ доступа недействителен — обратитесь к администратору"


def too_many_requests(platform: str) -> str:
    return f"{platform}: слишком много запросов, повторите позже"


def source_not_found(platform: str) -> str:
    return f"{platform}: источник не найден на площадке — проверьте ссылку"
